vim.opt.tabstop = 4       -- A tab character will be displayed as 4 spaces
vim.opt.shiftwidth = 4    -- Auto-indent operations (like `>>` or `==`) will use 4 spaces
vim.opt.expandtab = true  -- Insert spaces when the Tab key is pressed instead of a tab character
vim.opt.softtabstop = 4   -- Add/remove 4 spaces when pressing Tab or Backspace
vim.opt.autoindent = true -- Copy the indentation from the previous line
